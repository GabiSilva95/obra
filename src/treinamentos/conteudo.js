/** Módulos que o usuário pode ver (mesma regra do menu). */
export function modulosPermitidos(menuPermitido) {
  const ids = new Set(menuPermitido.map(m => m.id));
  return MODULOS.filter(m => !m.menuId || ids.has(m.menuId));
}
